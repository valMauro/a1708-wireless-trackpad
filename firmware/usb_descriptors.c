static char const *strings[] = {
  (const char[]){ 0x09, 0x04 },
  "Fai da te",
  "Trackpad A1708",
  NULL,                     /* numero di serie dal chip */
  "Trackpad mouse",
  "Trackpad Precision Touchpad",
  "Trackpad diagnostica",
};
static uint16_t desc_str[40];
uint16_t const *tud_descriptor_string_cb(uint8_t index, uint16_t langid) {
  (void)langid;
  uint8_t n;
  if (index == 0) { memcpy(&desc_str[1], strings[0], 2); n = 1; }
  else {
    char serial[2 * PICO_UNIQUE_BOARD_ID_SIZE_BYTES + 1];
    const char *s;
    if (index == 3) { pico_get_unique_board_id_string(serial, sizeof serial); s = serial; }
    else if (index < sizeof strings / sizeof strings[0]) s = strings[index];
    else return NULL;
    n = (uint8_t)strlen(s); if (n > 39) n = 39;
    for (uint8_t i = 0; i < n; i++) desc_str[1 + i] = s[i];
  }
  desc_str[0] = (uint16_t)((TUSB_DESC_STRING << 8) | (2 * n + 2));
  return desc_str;
}

